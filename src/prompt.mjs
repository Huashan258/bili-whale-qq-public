/** 补话时给模型的上下文 */
export function catchUpPrompt({ groupName, lines, title, titles }) {
  const body = lines.map((l) => `${l.admin ? '【主人】' : l.self ? '→ ' : ''}${l.name}：${l.text}`).join('\n')
  const pool = (titles ?? []).length > 1 ? `他说换个称呼，就从这些里另挑一个：${titles.join('、')}。` : ''
  const who = title
    ? `（标了【主人】的是你的主人本人，这轮要称呼他，就用「${title}」。${pool}）`
    : '（标了【主人】的是你的主人本人，其余都是群友，别叫错。）'
  return `群：${groupName}
${who}
（距上次说话过了一会儿，群里没接上。你可以补一句，也可以继续不说。）

最近的聊天，从旧到新：
${body}`
}

