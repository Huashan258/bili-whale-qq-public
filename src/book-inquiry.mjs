// Turn questions into dimension-qualified retrieval plans, not assumed user emotions.
export function inquiryIntent(input) {
  const text=String(input??'').trim()
  if (!/(?:怎么|如何|怎样|该.{0,5}(?:说|表达|回应|安慰)|能不能|可不可以|有什么|什么|哪(?:句|段|首|种|些)|请问|请教|能否|是否|为什么|为何|何以|[？?])/.test(text)) return null
  if (/代码|报错|数据库|端口|接口|配置|token|安装|原文|出处|翻译|论文|查询|查一下/.test(text)) return null
  if (/你.{0,5}(?:喜欢|在乎).{0,3}我/.test(text)&&!/怎么|如何|怎样|表达|说/.test(text)) return null
  if (/吃白饭|有什么本事|有何能耐/.test(text)&&!/怎么|如何|怎样|为什么|为何|何以/.test(text)) return null
  const dimensions={},cues=[]
  const add=(d,t)=>{dimensions[d]=[...new Set([...(dimensions[d]||[]),...t])].slice(0,4)}
  const concepts=[
    [/喜欢|喜爱|爱慕|心意|表白/,{'情感':['喜悦'],'主题':/恋人|爱人|爱慕|心上人|表白/.test(text)?['爱情']:['友情'],'用途':['人际交往']},['相知','相悦','相亲','投我','永以为好','欢喜','知己','喜见','相逢']],
    [/开心|高兴|喜悦|庆祝|祝贺|生日|祝福|祝愿/,{'情感':['喜悦'],'用途':['人际交往']},['喜','乐','欢','笑']],
    [/想念|思念|牵挂|想家/,{'情感':['思念'],'主题':/父母|家人|想家/.test(text)?['亲情']:['友情'],'用途':['人际交往']},['相思','思归','故人','思乡','怀人','思君']],
    [/感谢|感激|谢意|报答/,{'主题':['友情','仁爱'],'用途':['人际交往']},['报','赠','恩','投我','知己']],
    [/道歉|认错|歉意|悔过/,{'主题':['诚信','礼仪'],'用途':['修身养性','人际交往']},['过','改','省','诚','信']],
    [/安慰|难过|失落|悲伤|失败|鼓励/,{'情感':['宁静','豪迈'],'用途':['情绪慰藉'],'主题':['友情','仁爱']},['自宽','长风破浪','故人','春风','安心']],
    [/告别|送别|离别|分别/,{'主题':['离别','友情'],'用途':['人际交往']},['送','别','故人','相逢']],
    [/勇敢|勇气|勇往直前/,{'情感':['豪迈'],'用途':['修身养性']},['壮志','长风破浪','勇','不惧']],
    [/学习|读书|求学|勤学/,{'主题':['学习'],'用途':['教育教化','修身养性']},['学','读书','知之','诲']],
    [/守信|诚信|信用|承诺/,{'主题':['诚信'],'用途':['修身养性','人际交往']},['信','诚','诺']],
    [/节俭|清贫|知足|粗茶淡饭|吃白饭/,{'主题':['哲思'],'用途':['修身养性']},['疏食','自乐','知足','贫','不改其乐']],
  ]
  for(const [re,dims,words] of concepts)if(re.test(text)){for(const [d,t] of Object.entries(dims))add(d,t);cues.push(...words)}
  const scenes=[[/月夜|月亮|明月|夜晚|夜色/,'月夜'],[/春天|春日|春景|桃花/,'春景'],[/夏天|夏日|夏景|荷花/,'夏景'],[/秋天|秋日|秋景|秋风/,'秋景'],[/冬天|冬日|冬景|下雪|雪景/,'冬景'],[/宴饮|喝酒|饮酒|聚餐|酒席/,'宴饮'],[/旅途|旅行|远行|出游/,'旅途'],[/登临|登高|登山|登楼/,'登临']]
  for(const [re,tag] of scenes)if(re.test(text))add('场景',[tag])
  for(const tag of ['友情','亲情','仁爱','礼仪','山水','田园','哲思','民生'])if(text.includes(tag))add('主题',[tag])
  if (/父母|家人|母亲|父亲|爸妈/.test(text))add('主题',['亲情'])
  for(const author of ['李白','杜甫','陶渊明','苏轼','王维','白居易','孔子','孟子'])if(text.includes(author))add('作者',[author])
  for(const genre of ['诗歌','书信','语录','散文','对联'])if(text.includes(genre))add('体裁',[genre])
  if(!Object.keys(dimensions).length)return null
  return {inquiry:true,explicit:true,mood:'询问表达',tone:'提问或请教表达方法，不等于向机器人倾诉或示爱',
    goal:'直接回答本次问题或提供可用的表达示例；按主题、场景、用途、情感等维度找贴切材料，化用自然，不把表达示例当作本仙自己的表白',
    dimensions,cues:[...new Set(cues)].slice(0,24),query:text.slice(0,500)}
}
// Explicit questions bypass the automatic expression cooldown.
